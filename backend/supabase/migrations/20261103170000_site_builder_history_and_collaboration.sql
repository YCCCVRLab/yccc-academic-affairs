-- Site Builder revision history, undo, and private realtime collaboration.
-- Revisions are snapshots, not a second copy of the live site. Only admins can
-- read or write them, and every insert is stamped from the authenticated JWT.

create table if not exists public.aa_site_revisions (
  id bigint generated by default as identity primary key,
  entity_type text not null check (entity_type in ('page', 'settings')),
  entity_id text not null,
  action text not null default 'save' check (action in ('baseline', 'create', 'draft', 'publish', 'settings', 'delete', 'reorder', 'restore', 'undo')),
  previous_snapshot jsonb,
  snapshot jsonb not null,
  actor_user_id uuid references auth.users(id) on delete set null,
  actor_email text not null default '',
  created_at timestamp with time zone not null default now()
);

create index if not exists aa_site_revisions_entity_idx
  on public.aa_site_revisions (entity_type, entity_id, created_at desc);

alter table public.aa_site_revisions enable row level security;
grant select, insert on public.aa_site_revisions to authenticated;
grant usage, select on sequence public.aa_site_revisions_id_seq to authenticated;

-- Seed a baseline so the first undo has somewhere safe to return to.
insert into public.aa_site_revisions
  (entity_type, entity_id, action, previous_snapshot, snapshot, actor_email, created_at)
select 'page', p.slug, 'baseline', null, to_jsonb(p), 'System baseline', coalesce(p.updated_at, now())
from public.aa_site_pages p
where not exists (
  select 1 from public.aa_site_revisions r
  where r.entity_type = 'page' and r.entity_id = p.slug and r.action = 'baseline'
);

insert into public.aa_site_revisions
  (entity_type, entity_id, action, previous_snapshot, snapshot, actor_email, created_at)
select 'settings', 'singleton', 'baseline', null, to_jsonb(s), 'System baseline', coalesce(s.updated_at, now())
from public.aa_site_settings s
where s.singleton = true
  and not exists (
    select 1 from public.aa_site_revisions r
    where r.entity_type = 'settings' and r.entity_id = 'singleton' and r.action = 'baseline'
  );

create or replace function private.aa_stamp_site_revision_actor()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  new.actor_user_id := auth.uid();
  new.actor_email := coalesce(auth.jwt() ->> 'email', '');
  return new;
end;
$$;

drop trigger if exists aa_stamp_site_revision_actor on public.aa_site_revisions;
create trigger aa_stamp_site_revision_actor
  before insert on public.aa_site_revisions
  for each row execute function private.aa_stamp_site_revision_actor();

drop policy if exists "admins read site revisions" on public.aa_site_revisions;
create policy "admins read site revisions"
  on public.aa_site_revisions for select
  to authenticated
  using (private.aa_is_admin());

drop policy if exists "admins insert site revisions" on public.aa_site_revisions;
create policy "admins insert site revisions"
  on public.aa_site_revisions for insert
  to authenticated
  with check (private.aa_is_admin());

